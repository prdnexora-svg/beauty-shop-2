// NEXORA LUXE — SUPPLIER DIRECTORY SAMPLE DATASET (SEED)
// ----------------------------------------------------------------------------
// This is the local, self-contained dataset that powers the Supplier Directory
// page so its filters, search and category selections work out-of-the-box in
// any environment (including previews with no Supabase / DB rows configured).
//
// When the live service (Supabase or the local relational store) returns
// supplier rows, those rows take precedence; otherwise the directory falls
// back to this seed so every interactive control has data to operate on.
//
// The records deliberately span every filter dimension used by
// SupplierDirectoryScreen: business type, city / industrial hub, category,
// production scale (MOQ, monthly capacity, lead time), certifications,
// distance (radius), ratings, year established, employee count and the quick
// filters (verified, OEM/private label, ready to supply, top rated, fast
// response, low MOQ, pan India).
// ============================================================================

import type { VerifiedSupplier } from '../types';

/**
 * Build a fully-populated directory record from a compact spec. Keeps the seed
 * readable while guaranteeing every field the UI depends on is present.
 */
function supplier(spec: Partial<VerifiedSupplier> & Pick<VerifiedSupplier, 'id' | 'name' | 'type' | 'city' | 'state' | 'categories'>): VerifiedSupplier {
  const isVerified = spec.isVerified ?? true;
  const trustScore = spec.trustScore ?? (isVerified ? 90 : 64);
  const overallRating = spec.overallRating ?? Math.round((trustScore / 20) * 10) / 10;
  const establishedYearNumber = spec.establishedYearNumber ?? (spec.establishedYear ? parseInt(spec.establishedYear, 10) : 2014);
  const establishedYear = spec.establishedYear ?? String(establishedYearNumber);

  return {
    shortCode: spec.shortCode ?? spec.name.replace(/[^A-Za-z0-9]/g, '').slice(0, 4).toUpperCase(),
    isGstVerified: spec.isGstVerified ?? true,
    isIsoCertified: spec.isIsoCertified ?? false,
    isGmpCertified: spec.isGmpCertified ?? false,
    isFdaRegistered: spec.isFdaRegistered ?? false,
    isOrganicCertified: spec.isOrganicCertified ?? false,
    isCrueltyFree: spec.isCrueltyFree ?? false,
    readyToSupply: spec.readyToSupply ?? isVerified,
    distanceKm: spec.distanceKm ?? 0,
    moqNumber: spec.moqNumber,
    monthlyCapacityUnits: spec.monthlyCapacityUnits,
    leadTimeDays: spec.leadTimeDays,
    panIndia: spec.panIndia ?? false,
    serviceAreas: spec.serviceAreas ?? (spec.panIndia ? ['Pan India'] : [spec.city]),
    isVerifiedSupplier: isVerified,
    status: spec.status ?? (isVerified ? 'active' : 'pending_verification'),
    onboardingStatus: spec.onboardingStatus ?? (isVerified ? 'approved' : 'business_pending'),
    about: spec.about ?? `${spec.name} is a ${spec.type.toLowerCase()} of ${spec.categories.join(', ')} based in ${spec.city}, ${spec.state}.`,
    phone: spec.phone ?? '+91-98200-00000',
    whatsapp: spec.whatsapp ?? '+91-98200-00000',
    responseRate: spec.responseRate ?? (isVerified ? '98% (<2h)' : '82% (<24h)'),
    trustScore,
    reliabilityRating: spec.reliabilityRating ?? overallRating,
    productQualityRating: spec.productQualityRating ?? overallRating,
    overallRating,
    totalReviewsCount: spec.totalReviewsCount ?? 120,
    responseScore: spec.responseScore ?? Math.round(trustScore),
    responseTimeText: spec.responseTimeText ?? '2 Hours',
    exportReadiness: spec.exportReadiness ?? (isVerified ? 94 : 60),
    establishedYear,
    establishedYearNumber,
    employeeCount: spec.employeeCount ?? '50-200',
    employeeCountNumber: spec.employeeCountNumber ?? 80,
    monthlyCapacity: spec.monthlyCapacity ?? 'Contact for capacity',
    facilityArea: spec.facilityArea ?? '12,000 sq ft',
    moq: spec.moq ?? 'Contact for MOQ',
    verificationBadge: spec.verificationBadge ?? (isVerified ? 'Nexora Verified' : 'Pending Audit'),
    certificationsList: spec.certificationsList ?? (spec.isGstVerified ? ['GST'] : []),
    locationDetails: spec.locationDetails ?? {
      industrialZone: `${spec.city} Industrial Hub`,
      fullAddress: `${spec.city}, ${spec.state}, India`,
      city: spec.city,
      state: spec.state,
      lat: 19.076,
      lng: 72.8777,
      shippingHubs: [],
      rawMaterialSources: [],
      customsStatus: isVerified ? 'Export Ready' : 'Domestic',
      dispatchTurnaround: '3-5 Days',
      coldChainAvailable: false,
      transitAdvantage: 'Direct Access'
    },
    portfolioProducts: spec.portfolioProducts ?? [],
    complianceReports: spec.complianceReports ?? [],
    ...spec
  } as VerifiedSupplier;
}

